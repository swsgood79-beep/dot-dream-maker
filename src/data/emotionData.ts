export type EmoStage = 'CHILD' | 'TEEN' | 'YOUTH';
export type EmoTrigger = 'RANDOM' | 'CONTEST_LOSS' | 'STRIKE';
export type StepKind = 'EMPATHY' | 'LABEL' | 'LIMIT' | 'SOLVE';
/** 코칭이 아닌 흔한 반응 */
export type BadKind = 'DISMISS' | 'SUPPRESS' | 'LECTURE' | 'FIX' | 'THREAT' | 'PERMIT' | 'DIRECT' | 'FORGET';

export interface EmoScene {
  id: string;
  stage: EmoStage;
  trigger: EmoTrigger;
  emoji: string; // 장면 아이콘
  feel: string; // 아이 감정 이모지
  pose: string; // 처음 아이 모습 (기분 포즈 그림: mood_cry · mood_angry …)
  title: string;
  scene: string; // 상황 설명
  cry: string; // 아이가 처음 터뜨리는 말
  empathy: [string, string]; // [코칭 대사, 아이 반응]
  label: [string, string];
  fix: string; // '대신 해결해 주기' 선택지 (보상·해결) — 이름 붙이기 단계의 오답
  limit?: { behavior: string; good: string; reply: string }; // 물건 던지기·문 쾅 같은 행동이 있을 때만
  solve: [string, string];
}

